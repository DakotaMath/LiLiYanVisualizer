"""Generate the unrolled DOP853 step in site/sigma-kernel.js (between the GENERATED markers).

    python scripts/gen_sigma_kernel_js.py

The step is written out in full: scipy's DOP853 coefficients inlined, zero terms dropped, every
stage in local variables, the right-hand side (core.sigma_fast._rhs_into) inlined.  Sums are
taken in the same order as the numpy kernel (core.sigma_fast._shoot_block), so the two agree to
rounding.  JIT-compiled straight-line code like this runs several times faster than loops over
arrays.
"""
from __future__ import annotations

from pathlib import Path

from scipy.integrate._ivp import dop853_coefficients as C

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "site" / "sigma-kernel.js"
BEGIN = "// ---- GENERATED by scripts/gen_sigma_kernel_js.py: do not edit by hand ----"
END = "// ---- end of generated code ----"
NS = C.N_STAGES


def lit(v: float) -> str:
    r = repr(float(v))
    return f"({r})" if r.startswith("-") else r


def comb(coefs, k: int, i: int, skip_zero=True) -> str:
    """coefs[0]*K0_i + coefs[j]*Kj_i ... in the numpy kernel's order (first term always kept)."""
    terms = [f"{lit(coefs[0])} * k0_{i}"]
    for j in range(1, len(coefs)):
        if coefs[j] != 0.0:
            terms.append(f"{lit(coefs[j])} * k{j}_{i}")
    return " + ".join(terms)


def rhs(dst: int, T: str, Y: list[str]) -> list[str]:
    h, lz, f, Q, Qp = Y
    return [
        f"  e = Math.exp(-2.0 * Math.abs({T})); ip = 1.0 / (1.0 + e);",
        f"  th = ({T} < 0 ? -1.0 : 1.0) * ((1.0 - e) * ip); s2 = 4.0 * e * ip * ip;",
        f"  const k{dst}_0 = (1.0 + 0.5 * {Q}) - {h} * {h};",
        f"  const k{dst}_1 = {h};",
        f"  const k{dst}_2 = kap * Math.exp(-2.0 * {lz});",
        f"  const k{dst}_3 = {Qp};",
        f"  const k{dst}_4 = (lam - {f} * {f} + 2.0 * {Q}) * s2 - 4.0 * th * {Qp};",
    ]


def generate() -> str:
    L = [BEGIN,
         "// One DOP853 step of size hh from (t, y) with first stage fk.  Writes the new state to",
         "// OUT[0..4], the new derivative (FSAL) to OUT[5..9] and returns the error norm",
         "// (scipy's DOP853 norm: |hh| e5^2 / sqrt((e5^2 + 0.01 e3^2) * 5)).",
         "const OUT = new Float64Array(10);",
         "function dopStep(t, hh, y, fk, lam, kap, rtol, atol) {",
         "  const y_0 = y[0], y_1 = y[1], y_2 = y[2], y_3 = y[3], y_4 = y[4];",
         "  const k0_0 = fk[0], k0_1 = fk[1], k0_2 = fk[2], k0_3 = fk[3], k0_4 = fk[4];",
         "  let e, ip, th, s2;"]
    for s in range(1, NS):
        a = C.A[s, :s]
        Y = []
        for i in range(5):
            L.append(f"  const z{s}_{i} = ({comb(a, s, i)}) * hh + y_{i};")
            Y.append(f"z{s}_{i}")
        L += rhs(s, f"(t + {lit(C.C[s])} * hh)", Y)
    for i in range(5):
        L.append(f"  const yn_{i} = y_{i} + hh * ({comb(C.B, NS, i)});")
    L.append("  const tn = t + hh;")
    L += rhs(NS, "tn", [f"yn_{i}" for i in range(5)])
    L.append("  let e5n = 0.0, e3n = 0.0, sc, e5, e3;")
    for i in range(5):
        L.append(f"  sc = atol + Math.max(Math.abs(y_{i}), Math.abs(yn_{i})) * rtol;")
        L.append(f"  e5 = ({comb(C.E5, NS + 1, i)}) / sc; e3 = ({comb(C.E3, NS + 1, i)}) / sc;")
        L.append("  e5n += e5 * e5; e3n += e3 * e3;")
    L.append("  OUT[0] = yn_0; OUT[1] = yn_1; OUT[2] = yn_2; OUT[3] = yn_3; OUT[4] = yn_4;")
    L.append(f"  OUT[5] = k{NS}_0; OUT[6] = k{NS}_1; OUT[7] = k{NS}_2; OUT[8] = k{NS}_3; OUT[9] = k{NS}_4;")
    L.append("  const den = e5n + 0.01 * e3n;")
    L.append("  return den > 0 ? Math.abs(hh) * e5n / Math.sqrt(den * 5.0) : 0.0;")
    L.append("}")
    L.append(END)
    return "\n".join(L)


def main() -> None:
    src = TARGET.read_text(encoding="utf-8")
    a, b = src.index(BEGIN), src.index(END) + len(END)
    TARGET.write_text(src[:a] + generate() + src[b:], encoding="utf-8", newline="\n")
    print(f"wrote {TARGET}")


if __name__ == "__main__":
    main()

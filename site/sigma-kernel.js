  const ip = 1.0 / (1.0 + e);
  const th = (t < 0 ? -1.0 : 1.0) * ((1.0 - e) * ip);
  const s2 = 4.0 * e * ip * ip;
  const h = y[0], lz = y[1], f = y[2], Q = y[3], Qp = y[4];
  out[0] = (1.0 + 0.5 * Q) - h * h;
  out[1] = h;
  out[2] = kap * Math.exp(-2.0 * lz);
  out[3] = Qp;
  out[4] = (lam - f * f + 2.0 * Q) * s2 - 4.0 * th * Qp;

function initialStep(t, y, f0, d, lam, kap, rtol, atol, span) {
  let d0 = 0, d1 = 0;
  for (let i = 0; i < 5; i++) {
    sc[i] = atol + Math.abs(y[i]) * rtol;
    d0 += (y[i] / sc[i]) ** 2; d1 += (f0[i] / sc[i]) ** 2;
  }
  d0 = Math.sqrt(d0 / 5); d1 = Math.sqrt(d1 / 5);
  let h0 = (d0 < 1e-5 || d1 < 1e-5) ? 1e-6 : 0.01 * d0 / d1;
  h0 = Math.min(h0, span);
  for (let i = 0; i < 5; i++) yt[i] = y[i] + h0 * d * f0[i];
  rhs(f1, t + h0 * d, yt, lam, kap);
  let d2 = 0;
  for (let i = 0; i < 5; i++) d2 += ((f1[i] - f0[i]) / sc[i]) ** 2;
  d2 = Math.sqrt(d2 / 5) / h0;
  const m = Math.max(d1, d2);
  const h1 = m <= 1e-15 ? Math.max(1e-6, h0 * 1e-3) : (0.01 / m) ** (1.0 / 8.0);
  return Math.min(Math.min(100 * h0, h1), span);
}

/** Integrate one lane from t0 to target.  Returns {t, y, blow}. */
export function shootLane(y0, t0, target, lam, kap, rtol, atol, hBlow = MAP_H_BLOW) {
  const y = Float64Array.from(y0);
  let t = t0;
  if (Math.abs(target - t) === 0) return { t, y, blow: false };
  const d = target - t > 0 ? 1.0 : -1.0;
  const f = new Float64Array(5);
  rhs(f, t, y, lam, kap);
  let hs = initialStep(t, y, f, d, lam, kap, rtol, atol, Math.abs(target - t));
  for (let step = 0; step < MAX_STEPS; step++) {
    const hh = Math.min(hs, Math.abs(target - t)) * d;
    const err = dopStep(t, hh, y, f, lam, kap, rtol, atol);
    const ok = Number.isFinite(err);
    const accepted = ok && err <= 1.0;
    let fac = err === 0 ? MAX_FACTOR
      : Math.min(MAX_FACTOR, Math.max(MIN_FACTOR, SAFETY * (err > 0 ? err : 1.0) ** ERR_EXP));
    if (!accepted) fac = Math.min(fac, 1.0);
    if (!ok) fac = MIN_FACTOR;
    hs = Math.abs(hh) * fac;
    if (accepted) {
      t = t + hh;
      let fin = true;
      for (let i = 0; i < 5; i++) {
        y[i] = OUT[i]; f[i] = OUT[5 + i];
        if (!Number.isFinite(y[i])) fin = false;
      }
      if (Math.abs(y[0]) > hBlow || !fin) return { t, y, blow: true };
      if (Math.abs(target - t) <= 1e-12 * Math.max(1.0, Math.abs(target))) return { t, y, blow: false };
    }
    // a collapsing step is an integration failure, called a blow-up as in quick_pole
    if (hs < 1e-14 * Math.max(1.0, Math.abs(t))) return { t, y, blow: true };
  }
  return { t, y, blow: true };
}

/** quick_pole's rules: [code, mu, f_end, x_blowup] (NaN where undefined). */
export function classify(side, t, y, blow, kappa) {
  const h = y[0], f = y[2], Q = y[3];
  if (blow) {
    const xib = t - 1.0 / h;
    const bx = (Number.isFinite(h) && h !== 0 && Number.isFinite(xib)) ? Math.tanh(xib) : NaN;
    return [BLOWUP, NaN, NaN, bx];
  }
  const hm = side > 0 ? h : -h;
  const D = 1.0 + 0.5 * Q;
  if (!(D >= -1e-7 && hm > -Math.sqrt(Math.max(D, 0.0)) - 1e-7)) return [UNSAFE, NaN, f, NaN];
  const m = Math.sqrt(Math.max(D, 0.0)), xie = Math.abs(t);
  let code;
  if (kappa === 0.0) code = hm >= 0 ? G : R;
  else if (m < 0.5 / Math.max(xie, 1.0) || (m < 0.05 && hm > 3 * m)) code = xie * hm > 0.4 ? L1 : L2;
  else code = hm > 0 ? G : R;
  return [code, m, f, NaN];
}

/** Both poles at the point p = {c1, c2, c3, gamma, A, kappa}, base point xb. */
export function poles(p, xb, xiMax, rtol) {
  const lam = p.A ** 2 - 2 * p.c1 - 2 * p.c2 - 4 * p.c3;
  const kap = (1.0 - xb ** 2) * p.kappa;
  const Q0 = p.c1 * (1 - xb) + p.c2 * (1 + xb) + p.c3 * (1 - xb * xb);
  const Qx0 = -p.c1 + p.c2 - 2 * p.c3 * xb;
  const y0 = [0.5 * p.gamma + xb, 0.0, p.A, Q0, (1 - xb ** 2) * Qx0];
  const xi0 = Math.atanh(xb), atol = rtol * 1e-2;
  const n = shootLane(y0, xi0, xiMax, lam, kap, rtol, atol);
  const s = shootLane(y0, xi0, -xiMax, lam, kap, rtol, atol);
  return [classify(+1, n.t, n.y, n.blow, p.kappa), classify(-1, s.t, s.y, s.blow, p.kappa)];
}

function linspace(a, b, n) {             // numpy.linspace's values
  if (n === 1) return [a];
  const step = (b - a) / (n - 1), out = [];
  for (let i = 0; i < n; i++) out.push(a + i * step);
  out[n - 1] = b;
  return out;
}

/** The same rows, in the same JSON shape, as swirl_explorer.web.rows.sigma_rows. */
